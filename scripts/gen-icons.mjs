// Rebuilds src/components/icons.js from the approved desktop mock, so Remix
// draws the same Phosphor fill icons (MIT) the mock does.
//   node scripts/gen-icons.mjs [path-to-mock-noctivago-desktop.html]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const NAMES = ['audio-waveform', 'chevron-down', 'copy', 'headphones', 'minus', 'play', 'pause', 'plus', 'redo-2', 'refresh-cw', 'repeat', 'save', 'search', 'sparkles', 'trash-2', 'undo-2', 'volume-2', 'volume-x', 'shuffle', 'clock', 'x', 'layers', 'bookmark']
const mock = process.argv[2] || 'C:/Users/jluca/Projects/Global Management/design-system/dist/tool/mock-noctivago-desktop.html'
const html = fs.readFileSync(mock, 'utf-8')
const paths = {}
for (const name of NAMES) {
  const m = html.match(new RegExp(`<symbol id="i-${name}" viewBox="0 0 256 256">(.*?)</symbol>`))
  if (!m) throw new Error(`the mock has no icon "${name}"`)
  paths[name] = m[1]
}
const out = `// Generated by scripts/gen-icons.mjs from the approved desktop mock. Do not edit by hand.
// Phosphor fill icons (MIT), 256 grid, drawn with fill: currentColor.
const PATHS = ${JSON.stringify(paths, null, 2)}

export function icon(name, size = 16) {
  if (!PATHS[name]) throw new Error('Remix has no icon "' + name + '"')
  return '<svg class="rx-icon" width="' + size + '" height="' + size + '" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">' + PATHS[name] + '</svg>'
}

export const PLAY_ICON_SVG = icon('play')
export const PAUSE_ICON_SVG = icon('pause')
export const VOLUME_ICON_SVG = icon('volume-2')
export const MUTE_ICON_SVG = icon('volume-x')
`
fs.writeFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/components/icons.js'), out)
console.log(`${NAMES.length} icons written`)
